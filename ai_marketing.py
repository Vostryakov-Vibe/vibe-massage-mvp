def _generate_via_api(prompt: str) -> str | None:
    """Ступень 1: бесплатное текстовое API. None — если недоступно."""
    if not config.AI_API_URL or config.AI_API_URL.lower() in {"local", "offline", "none"}:
        logger.info("ИИ-API отключён в настройках — используем офлайн-шаблоны.")
        return None

    url = f"{config.AI_API_URL.rstrip('/')}/{urllib.parse.quote(prompt)}"
    params = {"model": "openai", "seed": random.randint(1, 10_000)}
    try:
        response = requests.get(url, params=params, timeout=config.AI_API_TIMEOUT)
        response.raise_for_status()
        text = response.text.strip()
    except requests.RequestException as error:
        logger.warning("ИИ-API недоступно (%s) — переключаемся на офлайн-шаблоны.", error)
        return None

    # API может вернуть как чистый текст, так и JSON — поддерживаем оба формата.
    if text.startswith("{"):
        try:
            payload = json.loads(text)
        except ValueError:
            return None
        text = (
            payload.get("choices", [{}])[0].get("message", {}).get("content")
            or payload.get("text")
            or ""
        ).strip()

    if len(text) < 120:
        logger.warning("ИИ-API вернуло слишком короткий ответ — используем шаблон.")
        return None
    return text


def _generate_from_template(topic: str, tone: str, length: str, keywords: str) -> str:
    """Ступень 2: офлайн-шаблон. Всегда доступен, структура соблюдена."""
    rng = random.Random()
    tone_key = tone if tone in HOOKS else TONES[0]
    hooks = HOOKS[tone_key]
    benefits = list(BENEFITS[tone_key])
    rng.shuffle(benefits)
    parts_count = BODY_PARTS_BY_LENGTH.get(length, 2)
    chosen_benefits = benefits[:parts_count]

    lines: list[str] = [_pick(hooks, rng), ""]

    if topic.strip():
        lines.append(f"Тема сегодняшнего разговора — {topic.strip().lower()}. 🤲")
        lines.append("")

    for benefit in chosen_benefits:
        lines.append(f"• {benefit}")

    keyword_text = _keyword_phrase(keywords)
    if keyword_text:
        lines.append("")
        lines.append(f"Особенно актуально, если вас беспокоит: {keyword_text}.")

    lines.append("")
    lines.append(_pick(CALLS_TO_ACTION[tone_key], rng))
    lines.append("")
    lines.append(_pick(HASHTAGS, rng))

    content = "\n".join(lines).strip()
    max_chars = MAX_CHARS_BY_LENGTH.get(length, 1200)
    if len(content) > max_chars:
        content = content[: max_chars - 3].rstrip() + "…"
    return content


def _has_cta_emoji(content: str) -> bool:
    """Есть ли в тексте эмодзи призыва к действию."""
    return any(symbol in content for symbol in CTA_EMOJI)


def _ensure_call_to_action(content: str, tone: str, rng: random.Random) -> str:
    """Гарантирует требование ТЗ: пост заканчивается призывом к действию с эмодзи.

    Бесплатное текстовое API не всегда соблюдает структуру поста, поэтому при
    отсутствии нужного эмодзи дописываем офлайн-призыв подходящей тональности.
    """
    if _has_cta_emoji(content):
        return content
    tone_key = tone if tone in CALLS_TO_ACTION else TONES[0]
    return f"{content.rstrip()}\n\n{_pick(CALLS_TO_ACTION[tone_key], rng)}"


def generate_post(topic: str, tone: str, length: str, keywords: str) -> dict:
    """Генерирует текст поста. Возвращает {"content": str, "source": str}."""
    prompt = build_prompt(topic, tone, length, keywords)
    rng = random.Random()

    api_text = _generate_via_api(prompt)
    if api_text:
        return {"content": _ensure_call_to_action(api_text, tone, rng), "source": "ai"}

    logger.info("Генерация выполнена офлайн-шаблоном (fallback).")
    return {
        "content": _ensure_call_to_action(
            _generate_from_template(topic, tone, length, keywords), tone, rng
        ),
        "source": "template",
    }
